function runCommand(command, args, cwd = REPO_ROOT) {
  const result = spawnSync(command, args, { cwd, stdio: 'pipe', encoding: 'utf8' });
  if (result.status !== 0) {
    const stderr = String(result.stderr || '').trim();
    throw new Error(`Command failed: ${command} ${args.join(' ')}${stderr ? `\n${stderr}` : ''}`);
  }
}

function ensureDir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true });
}

function clearDir(dirPath) {
  if (!fs.existsSync(dirPath)) return;
  fs.rmSync(dirPath, { recursive: true, force: true });
}

function readGeneratedMedia() {
  const fallback = {};
  if (!fs.existsSync(GENERATED_MEDIA_PATH)) return fallback;
  const raw = fs.readFileSync(GENERATED_MEDIA_PATH, 'utf8');
  const match = raw.match(/THEME_GENERATED_HOST_MEDIA\s*=\s*(\{[\s\S]*\});\s*$/m);
  if (!match) return fallback;
  try {
    return JSON.parse(match[1]);
  } catch {
    return fallback;
  }
}

function writeGeneratedMedia(map) {
  const content = [
    '// Auto-generated by scripts/installMappedHostVideos.cjs',
    '// Run npm run host:install-mapped-videos to refresh mappings.',
    `export const THEME_GENERATED_HOST_MEDIA = ${JSON.stringify(map, null, 2)};`,
    '',
  ].join('\n');
  fs.writeFileSync(GENERATED_MEDIA_PATH, content, 'utf8');
}

function toAssetPath(filePath) {
  return filePath.replace(REPO_ROOT, '').replaceAll(path.sep, '/').replace(/^\/public/, '');
}

function downloadVideos(downloadDir) {
  ensureDir(downloadDir);
  HOST_VIDEO_MAPPINGS.forEach(({ filename }) => {
    const sourceUrl = `${SOURCE_BASE_URL}/${filename}`;
    const outputPath = path.join(downloadDir, filename);
    runCommand('curl', ['-L', '--fail', '--max-time', '120', sourceUrl, '-o', outputPath]);
  });
}

function createHostVideoVariants(videoPath, hostDir) {
  const webmPath = path.join(hostDir, 'persona-host-talking.webm');
  const mp4Path = path.join(hostDir, 'persona-host-talking.mp4');
  const idlePath = path.join(hostDir, 'persona-host-idle.png');

  runCommand('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    '-i',
    videoPath,
    '-an',
    '-c:v',
    'libvpx-vp9',
    '-pix_fmt',
    'yuv420p',
    '-b:v',
    '0',
    '-crf',
    '34',
    '-row-mt',
    '1',
    '-deadline',
    'good',
    '-cpu-used',
    '2',
    '-vf',
    'fps=24,scale=min(960\\,iw):-2:flags=lanczos',
    webmPath,
  ]);

  runCommand('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    '-i',
    videoPath,
    '-an',
    '-c:v',
    'libx264',
    '-preset',
    'medium',
    '-crf',
    '23',
    '-movflags',
    '+faststart',
    '-pix_fmt',
    'yuv420p',
    '-vf',
    'fps=24,scale=min(960\\,iw):-2:flags=lanczos',
    mp4Path,
  ]);

  runCommand('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    '-i',
    videoPath,
    '-vf',
    'scale=min(960\\,iw):-2:flags=lanczos',
    '-frames:v',
    '1',
    idlePath,
  ]);

  return {
    idle: idlePath,
    webm: webmPath,
    mp4: mp4Path,
  };
}

function installThemeVideos(downloadDir) {
  const output = {};
  HOST_VIDEO_MAPPINGS.forEach(({ filename, themeName }) => {
    const themeSlug = THEME_SLUGS[themeName];
    if (!themeSlug) {
      throw new Error(`Missing slug for theme "${themeName}"`);
    }
    const videoPath = path.join(downloadDir, filename);
    const hostDir = path.join(THEMES_ROOT, themeSlug, 'hosts');
    ensureDir(hostDir);
    const media = createHostVideoVariants(videoPath, hostDir);
    output[themeName] = {
      hostDir,
      ...media,
    };
    console.log(`[installMappedHostVideos] Installed ${themeName} from ${filename}`);
  });
  return output;
}

function mergeGeneratedMedia(installedByTheme, existingMap) {
  const merged = { ...existingMap };

  Object.entries(installedByTheme).forEach(([themeName, media]) => {
    const existingEntry = merged[themeName] || {};
    const nextEntry = {
      ...existingEntry,
      personaHostIdle: toAssetPath(media.idle),
      talkingVideoWebm: toAssetPath(media.webm),
      talkingVideoMp4: toAssetPath(media.mp4),
      talkingVideo: toAssetPath(media.webm),
    };
    delete nextEntry.personaHostTalkingFrames;
    delete nextEntry.personaHostTalk1;
    delete nextEntry.personaHostTalk2;
    delete nextEntry.personaHostTalk3;
    const overlayPath = path.join(media.hostDir, 'host-overlay.png');
    if (fs.existsSync(overlayPath)) {
      nextEntry.hostOverlay = toAssetPath(overlayPath);
    }
    merged[themeName] = nextEntry;
  });

  return merged;
}

function main() {
  clearDir(TMP_ROOT);
  ensureDir(TMP_ROOT);
  const downloadDir = path.join(TMP_ROOT, 'downloads');

  downloadVideos(downloadDir);
  const installed = installThemeVideos(downloadDir);
  const existingMap = readGeneratedMedia();
  const mergedMap = mergeGeneratedMedia(installed, existingMap);
  writeGeneratedMedia(mergedMap);

  console.log('[installMappedHostVideos] Done.');
  console.log(`- Videos processed: ${HOST_VIDEO_MAPPINGS.length}`);
  console.log(`- Updated map: ${GENERATED_MEDIA_PATH}`);
}

try {
  main();
} catch (error) {
  console.error(`[installMappedHostVideos] ${error.message}`);
  process.exit(1);
}
