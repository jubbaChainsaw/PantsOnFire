#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const picturePacksRoot = path.join(repoRoot, 'public', 'assets', 'graphic-packs', 'picture');
const outputFile = path.join(repoRoot, 'src', 'data', 'generatedPictureDlcManifests.js');

function walk(dir, matches = []) {
  if (!fs.existsSync(dir)) return matches;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(fullPath, matches);
      continue;
    }
    if (entry.isFile() && entry.name === 'manifest.json') {
      matches.push(fullPath);
    }
  }
  return matches;
}

function loadManifest(filePath) {
  try {
    const raw = fs.readFileSync(filePath, 'utf8');
    const data = JSON.parse(raw);
    return data;
  } catch (error) {
    console.error(`[syncPictureDlcManifests] Failed to parse ${filePath}: ${error.message}`);
    return null;
  }
}

function validateManifest(manifest, filePath) {
  const problems = [];
  if (!manifest || typeof manifest !== 'object') problems.push('Manifest is not an object');
  if (!manifest?.id) problems.push('Missing id');
  if (!manifest?.category) problems.push('Missing category');
  if (manifest?.category && manifest.category !== 'picture') problems.push(`Unsupported category: ${manifest.category}`);
  if (!manifest?.basePath) problems.push('Missing basePath');
  if (!Array.isArray(manifest?.entries) || manifest.entries.length === 0) problems.push('entries must be a non-empty array');
  if (Array.isArray(manifest?.entries)) {
    const entryIds = new Set();
    manifest.entries.forEach((entry, index) => {
      if (!entry?.entryId) problems.push(`entries[${index}] missing entryId`);
      if (entry?.entryId) {
        if (entryIds.has(entry.entryId)) {
          problems.push(`entries[${index}] duplicate entryId "${entry.entryId}"`);
        } else {
          entryIds.add(entry.entryId);
        }
      }
      if (!entry?.main) problems.push(`entries[${index}] missing main`);
      if (!entry?.imposter) problems.push(`entries[${index}] missing imposter`);
      if (!entry?.mainMediaFile) problems.push(`entries[${index}] missing mainMediaFile`);
      if (!entry?.imposterMediaFile) problems.push(`entries[${index}] missing imposterMediaFile`);
      const mediaBase = path.join(repoRoot, 'public');
      const basePath = String(manifest?.basePath || '').replace(/^\/+/, '');
      const mainMediaPath = entry?.mainMediaFile ? path.join(mediaBase, basePath, entry.mainMediaFile) : null;
      const imposterMediaPath = entry?.imposterMediaFile ? path.join(mediaBase, basePath, entry.imposterMediaFile) : null;
      if (mainMediaPath && !fs.existsSync(mainMediaPath)) {
        problems.push(`entries[${index}] main media file missing at ${mainMediaPath}`);
      }
      if (imposterMediaPath && !fs.existsSync(imposterMediaPath)) {
        problems.push(`entries[${index}] imposter media file missing at ${imposterMediaPath}`);
      }
    });
  }
  if (problems.length) {
    console.error(`[syncPictureDlcManifests] Invalid manifest ${filePath}:`);
    problems.forEach((problem) => console.error(`  - ${problem}`));
    return false;
  }
  return true;
}

function sync() {
  const manifestFiles = walk(picturePacksRoot);
  const manifests = manifestFiles
    .map((filePath) => ({ filePath, manifest: loadManifest(filePath) }))
    .filter((item) => item.manifest)
    .filter((item) => validateManifest(item.manifest, item.filePath))
    .map((item) => item.manifest);

  manifests.sort((a, b) => String(a.id).localeCompare(String(b.id)));

  const header = `// Auto-generated by scripts/syncPictureDlcManifests.cjs\n` +
    `// Do not edit by hand. Edit manifest.json files in public/assets/graphic-packs/picture/*/.\n\n`;
  const body = `export const PICTURE_DLC_MANIFESTS = ${JSON.stringify(manifests, null, 2)};\n`;
  fs.writeFileSync(outputFile, header + body, 'utf8');
  console.log(`[syncPictureDlcManifests] Wrote ${outputFile} (${manifests.length} manifests)`);
}

sync();
