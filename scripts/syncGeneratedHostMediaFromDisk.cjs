#!/usr/bin/env node
/**
 * Refresh src/data/generatedHostMedia.js from on-disk theme host folders.
 * Drops hostOverlay when overlay PNG is missing (video + idle hosts).
 */
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const themesRoot = path.join(repoRoot, 'public', 'assets', 'themes');
const outPath = path.join(repoRoot, 'src', 'data', 'generatedHostMedia.js');

const THEME_SLUG_TO_NAME = {
  default: 'Default',
  'murder-mystery': 'Murder Mystery',
  pirates: 'Pirates',
  'cops-and-robbers': 'Cops and Robbers',
  'ghosts-and-ghouls': 'Ghosts and Ghouls',
  gangsters: 'Gangsters',
  cowboys: 'Cowboys',
  wrestlers: 'Wrestlers',
  'rock-stars': 'Rock Stars',
  'flying-squad': 'Flying Squad',
  aliens: 'Aliens',
  medical: 'Medical',
  royalty: 'Royalty',
  vikings: 'Vikings',
  cyberpunk: 'Cyberpunk',
  ninjas: 'Ninjas',
  'mythology-gods-legends': 'Mythology (Gods & Legends)',
  'post-apocalypse': 'Post-Apocalypse',
  carnival: 'Carnival',
  'wizards-witches': 'Wizards & Witches',
  'time-travelers': 'Time Travelers',
  gladiators: 'Gladiators',
  cartoons: 'Cartoons',
  'sci-fi': 'Sci-Fi',
  'under-the-sea': 'Under the Sea',
  anime: 'Anime',
  military: 'Military',
  animals: 'Animals',
  medieval: 'Medieval',
  sports: 'Sports',
  'law-and-order': 'Law and Order',
};

function fileExists(relPath) {
  return fs.existsSync(path.join(repoRoot, 'public', relPath.replace(/^\//, '')));
}

function buildEntry(slug) {
  const base = `/assets/themes/${slug}/hosts`;
  const entry = {};
  const idle = `${base}/persona-host-idle.png`;
  const overlay = `${base}/host-overlay.png`;
  const webm = `${base}/persona-host-talking.webm`;
  const mp4 = `${base}/persona-host-talking.mp4`;

  if (fileExists(idle)) entry.personaHostIdle = idle;
  if (fileExists(overlay)) entry.hostOverlay = overlay;
  if (fileExists(webm)) {
    entry.talkingVideoWebm = webm;
    entry.talkingVideo = webm;
  }
  if (fileExists(mp4)) entry.talkingVideoMp4 = mp4;

  return Object.keys(entry).length ? entry : null;
}

function main() {
  if (!fs.existsSync(themesRoot)) {
    console.error('[syncGeneratedHostMediaFromDisk] Missing themes root');
    process.exit(1);
  }

  const media = {};
  for (const slug of fs.readdirSync(themesRoot)) {
    const hostsDir = path.join(themesRoot, slug, 'hosts');
    if (!fs.statSync(path.join(themesRoot, slug)).isDirectory()) continue;
    if (!fs.existsSync(hostsDir)) continue;
    const themeName = THEME_SLUG_TO_NAME[slug];
    if (!themeName) continue;
    const entry = buildEntry(slug);
    if (entry) media[themeName] = entry;
  }

  const lines = [
    '// Auto-generated by scripts/syncGeneratedHostMediaFromDisk.cjs',
    '// Run after changing theme host video/idle assets.',
    'export const THEME_GENERATED_HOST_MEDIA = {',
  ];
  for (const [themeName, entry] of Object.entries(media).sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  ${JSON.stringify(themeName)}: {`);
    for (const [key, value] of Object.entries(entry)) {
      lines.push(`    ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
    }
    lines.push('  },');
  }
  lines.push('};', '');

  fs.writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');
  console.log(`[syncGeneratedHostMediaFromDisk] Wrote ${Object.keys(media).length} themes -> ${outPath}`);
}

main();
